#!/usr/bin/env python3
"""gen_sds_rxcal — extract Linux's RTL930x SerDes RX calibration into shared/rtl930x-sds-rxcal/ (#83, #114).

- Source: drivers/net/pcs/pcs-rtl-otto.c of the pinned kernel tree (default: the OpenWrt build tree of this repo).
- Takes `rtpcs_930x_sds_rx_calibrate` and every static function it reaches in that file, verbatim, in source order.
- Writes rtl930x_sds_rxcal.c (functions) + MANIFEST.txt (source sha256, kernel version, function list, symbols the stub
  header must provide). Hand-written glue lives in rtl930x_sds_rxcal_stub.h (never overwritten).
- `check`: re-extract to memory and fail on drift against the committed copy (run from dev.py gate).
- Log: tmp/logs/gen_sds_rxcal.log

Usage: scripts/gen_sds_rxcal.py [stage|check] [--src PATH]
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "shared/rtl930x-sds-rxcal"
LOG = ROOT / "tmp/logs/gen_sds_rxcal.log"
DEFAULT_SRC = Path("/home/dan/st1008f-scratch/openwrt-build/build_dir/target-mips_24kc_musl/linux-realtek_rtl930x/linux-7.4-rc3"
                   "/drivers/net/pcs/pcs-rtl-otto.c")
ROOT_FN = "rtpcs_930x_sds_rx_calibrate"
FN_START = re.compile(r"^(?:static\s+)?(?:inline\s+)?(?:const\s+)?[A-Za-z_][\w\s\*]*?\b(rtpcs_\w+)\s*\(", re.M)


def log(msg: str) -> None:
    line = f"{time.strftime('%Y-%m-%dT%H:%M:%S%z')} {msg}"
    print(line, flush=True)
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with LOG.open("a") as fh:
        fh.write(line + "\n")


def functions(text: str) -> dict[str, tuple[int, int]]:
    """name -> (start offset incl. leading comment, end offset) of every top-level function definition."""
    out: dict[str, tuple[int, int]] = {}
    for m in FN_START.finditer(text):
        name = m.group(1)
        # definition = the '{' that follows the closing ')' at column 0 context, not a prototype
        i = text.find("{", m.end())
        j = text.find(";", m.end())
        if i < 0 or (0 <= j < i):
            continue
        depth, k = 0, i
        while k < len(text):
            c = text[k]
            depth += c == "{"
            depth -= c == "}"
            k += 1
            if depth == 0:
                break
        start = m.start()
        # pull in an immediately preceding block comment
        pre = text.rfind("\n\n", 0, start)
        head = text[pre + 2:start] if pre >= 0 else ""
        if head.strip().startswith("/*") and head.strip().endswith("*/"):
            start = pre + 2
        out[name] = (start, k)
    return out


def closure(text: str, fns: dict[str, tuple[int, int]]) -> list[str]:
    seen: set[str] = set()
    todo = [ROOT_FN]
    while todo:
        n = todo.pop()
        if n in seen or n not in fns:
            continue
        seen.add(n)
        body = text[fns[n][0]:fns[n][1]]
        todo += [c for c in re.findall(r"\b(rtpcs_\w+)\s*\(", body) if c != n]
    return sorted(seen, key=lambda n: fns[n][0])


def build(src: Path) -> tuple[str, str]:
    text = src.read_text()
    fns = functions(text)
    if ROOT_FN not in fns:
        sys.exit(f"FAIL: {ROOT_FN} not found in {src}")
    names = closure(text, fns)
    body = "\n\n".join(text[fns[n][0]:fns[n][1]].rstrip() for n in names)
    defined = set(fns)
    ext_calls = sorted(set(re.findall(r"\b(rtpcs_\w+)\s*\(", body)) - set(names) - {"rtpcs_sds_write", "rtpcs_sds_read"} & defined - set(names))
    syms = sorted(set(re.findall(r"\b(RTPCS_\w+|rtpcs_\w+_t|enum rtpcs_\w+)", body)) | set(re.findall(r"\b(dev_\w+|msleep|usleep_range|udelay|mdelay|time_\w+|FIELD_\w+|BIT|GENMASK|min|max|ARRAY_SIZE)\b", body)))
    sha = hashlib.sha256(text.encode()).hexdigest()
    kver = re.search(r"linux-(\d+\.\d+[\w\-\.]*)", str(src))
    header = (f"/* Generated by scripts/gen_sds_rxcal.py from {src.name} (kernel {kver.group(1) if kver else '?'}, "
              f"sha256 {sha[:16]}); do not edit.\n * Origin: Linux drivers/net/pcs/pcs-rtl-otto.c, GPL-2.0-only.\n"
              f" * Glue: rtl930x_sds_rxcal_stub.h */\n")
    man = [f"source {src}", f"sha256 {sha}", f"kernel {kver.group(1) if kver else '?'}", f"root {ROOT_FN}",
           f"functions {len(names)}: " + " ".join(names), "needed from stub/outside: " + " ".join(syms)]
    if ext_calls:
        man.append("calls to functions outside the closure: " + " ".join(ext_calls))
    return header + "\n" + body + "\n", "\n".join(man) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("mode", nargs="?", default="stage", choices=["stage", "check"])
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    a = ap.parse_args()
    if not a.src.is_file():
        sys.exit(f"FAIL: source {a.src} missing")
    code, man = build(a.src)
    cfile, mfile = OUT / "rtl930x_sds_rxcal.c", OUT / "MANIFEST.txt"
    if a.mode == "check":
        ok = cfile.exists() and cfile.read_text() == code and mfile.read_text() == man
        log(f"{'OK' if ok else 'DRIFT'}: {cfile.relative_to(ROOT)} vs {a.src.name}")
        return 0 if ok else 1
    OUT.mkdir(parents=True, exist_ok=True)
    cfile.write_text(code)
    mfile.write_text(man)
    n = man.splitlines()[4].split(":")[0]
    log(f"staged {cfile.relative_to(ROOT)} ({len(code.splitlines())} lines), {n}")
    print(man)
    return 0


if __name__ == "__main__":
    sys.exit(main())
