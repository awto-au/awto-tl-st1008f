#!/usr/bin/env python3
"""sds_tables_gen — emit the stock 10GBASE-R SerDes construct patch lists as a C header.

- Source: stock loader (private/stock-loader-20261007/loader.bin), VA = off - 0x5080 + 0x83f00000.
- Sets: default even-sds 0x83faf52c / odd-sds 0x83faf680 (17 rows each); row = {mode, flag, sub, list, n};
  picks mode 2 (10GR) sub 0 (no PHY). Same data as SDK rtl9300_a_sds_10gr_lane0/1 (dal_longan_construct.c).
- Output: uboot-port/board/tplink/tl-st1008f/rtk_sds_tables.h. Log: tmp/logs/sds_tables_gen.log.
"""

import struct
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOADER = ROOT / "private/stock-loader-20261007/loader.bin"
OUT = ROOT / "uboot-port/board/tplink/tl-st1008f/rtk_sds_tables.h"
LOG = ROOT / "tmp/logs/sds_tables_gen.log"
SETS = {"even": (0x83faf52c, 17, 120), "odd": (0x83faf680, 17, 106)}  # (va, rows, expected n)


def log(msg: str) -> None:
    line = f"{time.strftime('%Y-%m-%dT%H:%M:%S%z')} {msg}"
    print(line, flush=True)
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with LOG.open("a") as fh:
        fh.write(line + "\n")


def main() -> int:
    if not LOADER.exists():
        log(f"missing {LOADER.relative_to(ROOT)} (private/, local only)")
        return 1
    d = LOADER.read_bytes()

    def off(va: int) -> int:
        return va - 0x83F00000 + 0x5080

    out = ["/* SPDX-License-Identifier: GPL-2.0+ */",
           "/* Generated by scripts/sds_tables_gen.py from the stock loader; do not edit.",
           " * RTL9300 10GBASE-R SerDes construct lists (= SDK rtl9300_a_sds_10gr_lane0/1). */",
           "", "struct sds_cfg { u8 page, reg; u16 data; };", ""]
    for name, (va, rows, want) in SETS.items():
        hit = None
        for i in range(rows):
            mode, _flag, sub, ptr, cnt = struct.unpack(">5I", d[off(va + 20 * i):off(va + 20 * i) + 20])
            if mode == 2 and sub == 0:
                hit = (ptr, cnt)
        if not hit or hit[1] != want:
            log(f"FAIL {name}: 10GR list {hit} (want n={want})")
            return 1
        ptr, cnt = hit
        out.append(f"/* {name} SerDes: stock list 0x{ptr:08x}, {cnt} rows */")
        out.append(f"static const struct sds_cfg sds_10gr_{name}[] = {{")
        for j in range(cnt):
            pg, rg, dt = struct.unpack(">3H", d[off(ptr) + 6 * j:off(ptr) + 6 * j + 6])
            out.append(f"\t{{ 0x{pg:02x}, 0x{rg >> 8:02x}, 0x{dt:04x} }},")
        out.append("};")
        out.append("")
        log(f"{name}: 0x{ptr:08x} n={cnt}")
    OUT.write_text("\n".join(out))
    log(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
